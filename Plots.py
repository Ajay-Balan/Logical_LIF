# 2. XOR Network Implementation
# =============================================================================
def simulate_XOR():
    print("\nXOR Gate Results:")
    inputs = [(0, 0), (0, 1), (1, 0), (1, 1)]

    for A, B in inputs:
        start_scope()

        # ---------------------
        # Layer 1: Hidden Neurons
        # ---------------------
        layer1_eqs = '''
        dv/dt = (I - v)/(10*ms) : 1
        I : 1
        '''
        layer1 = NeuronGroup(2, layer1_eqs,
                             threshold='v > 1.0',
                             reset='v = 0',
                             method='exact')
        # Weighted current injection for A∧¬B and ¬A∧B
        layer1.I = [2.0*A - 2.0*B, -2.0*A + 2.0*B]

        # ---------------------
        # Layer 2: Output Neuron (OR of Layer 1)
        # ---------------------
        layer2_eqs = '''
        dv/dt = (I - v)/(10*ms) : 1
        I : 1
        '''
        layer2 = NeuronGroup(1, layer2_eqs,
                             threshold='v > 0.9',
                             reset='v = 0',
                             refractory=5*ms,
                             method='exact')

        # Synapse: Current-based summation from both layer1 neurons
        syn = Synapses(layer1, layer2,
                       'w : 1',
                       on_pre='I_post += w')
        syn.connect(i=[0, 1], j=0)
        syn.w = [1.5, 1.5]  # Boosted weights for reliable firing

        # ---------------------
        # Monitors
        # ---------------------
        m1 = StateMonitor(layer1, 'v', record=True)
        m2 = StateMonitor(layer2, 'v', record=True)
        spike_mon_layer2 = SpikeMonitor(layer2)

        # ---------------------
        # Run simulation
        # ---------------------
        net = Network(layer1, layer2, syn, m1, m2, spike_mon_layer2)
        net.run(25*ms)  # Slightly longer to allow late spikes

        # ---------------------
        # Output and Plot
        # ---------------------
        output = 1 if spike_mon_layer2.count[0] > 0 else 0
        print(f"Input ({A},{B}) → Output: {output}")

        # Plotting
        plt.figure(figsize=(8, 4))
        plt.plot(m1.t/ms, m1.v[0], label='Neuron 1 (A∧¬B)')
        plt.plot(m1.t/ms, m1.v[1], label='Neuron 2 (¬A∧B)')
        plt.plot(m2.t/ms, m2.v[0], 'k--', label='Output Neuron')
        plt.axhline(0.9, color='r', linestyle=':', label='Threshold')
        plt.title(f'XOR Gate: Input ({A},{B})')
        plt.xlabel('Time (ms)')
        plt.ylabel('Membrane Potential')
        plt.legend()
        plt.tight_layout()
        plt.savefig(f'XOR_{A}_{B}.png', dpi=150)
        plt.close()




