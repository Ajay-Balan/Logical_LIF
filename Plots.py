from brian2 import *
import matplotlib.pyplot as plt
import numpy as np

# =============================================================================
# 1. Core LIF Gate Implementations
# =============================================================================
def simulate_gate(gate_type, inputs, weights, threshold, runtime=30*ms):
    """Simulate LIF logic gate and plot membrane potential with spike indication."""
    print(f"\n{gate_type} Gate Results:")

    for inp in inputs:
        start_scope()

        # Define neuron group
        neuron = NeuronGroup(1,
            '''dv/dt = (I - v)/(10*ms) : 1
               I : 1 (shared)''',
            threshold=f'v > {threshold}',
            reset='v = 0',
            method='exact')

        # Assign input current
        if gate_type == 'NOT':
            A = inp
            neuron.I = weights[0]*A + weights[1]  # w_A*A + bias
        else:
            A, B = inp
            neuron.I = weights[0]*A + weights[1]*B

        # Monitors
        state_mon = StateMonitor(neuron, 'v', record=True)
        spike_mon = SpikeMonitor(neuron)

        # Run simulation
        net = Network(neuron, state_mon, spike_mon)
        net.run(runtime)

        # Determine output
        output = 1 if spike_mon.count[0] > 0 else 0
        print(f"Input {inp} → Output: {output}")

        # Plotting
        plt.figure(figsize=(4, 3))
        plt.plot(state_mon.t / ms, state_mon.v[0], label='Membrane Potential')
        plt.axhline(threshold, color='red', linestyle='--', label='Threshold')

        # Optional: mark spike times
        if spike_mon.count[0] > 0:
            for t in spike_mon.t:
                plt.axvline(t/ms, color='green', linestyle=':', label='Spike')

        plt.title(f'{gate_type} Gate: Input {inp} → Output: {output}')
        plt.xlabel('Time (ms)')
        plt.ylabel('Voltage')
        plt.legend()
        plt.tight_layout()
        plt.savefig(f'{gate_type}_input_{inp}.png', dpi=120)
        plt.close()


